// Install (or refresh) the per-user Startup entry that launches the panel.
//
//   node scripts/install-autostart.js           # install / update
//   node scripts/install-autostart.js --remove  # delete it
//
// No admin needed: it writes a .vbs into the current user's Startup folder.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const startupDir = path.join(
  process.env.APPDATA || '',
  'Microsoft',
  'Windows',
  'Start Menu',
  'Programs',
  'Startup'
)
const target = path.join(startupDir, 'MT5 Panel.vbs')

if (process.argv.includes('--remove')) {
  if (fs.existsSync(target)) {
    fs.unlinkSync(target)
    console.log('removed', target)
  } else {
    console.log('not installed')
  }
  process.exit(0)
}

const vbs = [
  "' Generated by scripts/install-autostart.js — starts the MT5 panel at logon.",
  'Set sh = CreateObject("WScript.Shell")',
  `sh.Run "cmd /c cd /d ""${root}"" && node server\\index.js", 0, False`,
  ''
].join('\r\n')

fs.mkdirSync(startupDir, { recursive: true })
fs.writeFileSync(target, vbs)
console.log('installed', target)
console.log('project root:', root)
